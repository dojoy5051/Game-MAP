export function getTerrainLabel(terrain: string): string {
  switch (terrain) {
    case 'capital':
      return 'Thủ Đô (+2 quân/lượt)';
    case 'fortress':
      return 'Pháo Đài (+1 phòng thủ)';
    case 'port':
      return 'Thương Cảng (+1 tiếp tế)';
    default:
      return 'Đồng Bằng';
  }
}
