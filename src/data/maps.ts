function normalizeScenario(scenario: MapScenario): MapScenario {
  const map = new Map(scenario.territories.map((t) => [t.id, t]));
  for (const t of scenario.territories) {
    for (const n of t.neighbors) {
      const target = map.get(n);
      if (target && !target.neighbors.includes(t.id)) {
        target.neighbors.push(t.id);
      }
    }
    if (t.seaLinks) {
      for (const s of t.seaLinks) {
        const target = map.get(s);
        if (target) {
          if (!target.neighbors.includes(t.id)) target.neighbors.push(t.id);
          if (!t.neighbors.includes(s)) t.neighbors.push(s);
          if (!target.seaLinks) target.seaLinks = [];
          if (!target.seaLinks.includes(t.id)) target.seaLinks.push(t.id);
        }
      }
    }
  }
  return scenario;
}

